(function () {
  let lang = 'ru';
  try { lang = localStorage.getItem('cvvizor.lang') || 'ru'; } catch (e) {}
  CV.getLang = () => lang;
  CV.setLang = l => { lang = l; try { localStorage.setItem('cvvizor.lang', l); } catch (e) {} };
  CV.t = (path, vars) => {
    let node = CV.I18N[lang];
    for (const k of path.split('.')) {
      if (node == null) return '?' + path;
      node = node[k];
    }
    if (typeof node !== 'string') return '?' + path;
    if (vars) for (const v of Object.keys(vars)) node = node.replace('{' + v + '}', vars[v]);
    return node;
  };
})();
